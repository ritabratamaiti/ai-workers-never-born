"""Collect every number the essay quotes, with its source, and write numbers.md / numbers.json.

The text of the essay should only use figures that appear in numbers.md, so each one can be
traced to the notebook cell that computed it.
"""
from __future__ import annotations

import json
from pathlib import Path


class Facts:
    def __init__(self):
        self.items = {}

    def __call__(self, key: str, value, what: str, source: str, fmt: str = "{:,.2f}"):
        value = value.item() if hasattr(value, "item") else value
        shown = fmt.format(value)
        self.items[key] = {"value": value, "display": shown, "what": what, "source": source}
        print(f"{key:<40} {shown:>10}   {what}")
        return value

    def write(self, folder: Path) -> Path:
        lines = ["# Numbers quoted in the essay", "",
                 "Generated by `story.py`; do not edit by hand. Each figure is printed by the cell that computes it.", "",
                 "| key | value | what | source |", "|---|---:|---|---|"]
        lines += [f"| `{k}` | {v['display']} | {v['what']} | {v['source']} |" for k, v in self.items.items()]
        (folder / "numbers.md").write_text("\n".join(lines) + "\n", "utf-8")
        (folder / "numbers.json").write_text(json.dumps(self.items, indent=2) + "\n", "utf-8")
        return folder / "numbers.md"
